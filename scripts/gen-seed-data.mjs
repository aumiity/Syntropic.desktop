// One-time / regenerable transform: docs/*.json (Hygeia + exported lookups)
//   → electron/db/seed-data/*.ts  (TS data modules, bundled into main.js by rollup)
//
// Run: node scripts/gen-seed-data.mjs
//
// Why TS modules instead of reading JSON at runtime: electron-builder only
// ships dist/ + dist-electron/. A bundled `import` is inlined into main.js by
// rollup, so the seed data travels with the app with zero path/packaging risk.
//
// Column adjustment (Hygeia / export shapes ≠ our SQLite schema):
//   drug_generic_names: schema = (name, is_disabled). Map Name→name. All source
//     rows are IsDisabled=0; drop every other Hygeia column (Code, DrugGroupKey,
//     IndicationNote, IsAntibiotic, Pregnancy*) — not in our schema.
//   label_frequencies / label_meal_relations: source already has `code` → pass through.
//   label_advices / label_dosages / label_times: source has NO `code`, but schema
//     makes `code` NOT NULL UNIQUE. `code` is never used in any join (all FKs use
//     id), so synthesize a stable unique code from the source id: zero-padded.
//   created_at / updated_at in source: dropped (schema has neither on label tables;
//     drug_generic_names.created_at defaults in SQL).

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const docs = join(root, 'docs')
const out = join(root, 'electron', 'db', 'seed-data')

const read = (f) => JSON.parse(readFileSync(join(docs, f), 'utf-8'))
const header = (src) =>
  `// AUTO-GENERATED by scripts/gen-seed-data.mjs from docs/${src}\n` +
  `// Do not edit by hand — re-run the generator instead.\n\n`

// ---- drug_generic_names ----------------------------------------------------
{
  const rows = read('DrugGenericName.json')
  const seen = new Set()
  const names = []
  for (const r of rows) {
    const name = String(r.Name ?? '').trim().replace(/\s+/g, ' ')
    if (!name) continue
    const k = name.toLowerCase()
    if (seen.has(k)) continue // de-dupe case-insensitively, keep first
    seen.add(k)
    names.push(name)
  }
  names.sort((a, b) => a.localeCompare(b))
  const body =
    header('DrugGenericName.json') +
    `const DRUG_GENERIC_NAMES: string[] = ${JSON.stringify(names, null, 0)}\n\n` +
    `export default DRUG_GENERIC_NAMES\n`
  writeFileSync(join(out, 'drug-generic-names.ts'), body)
  console.log(`drug-generic-names.ts: ${names.length} names`)
}

// ---- label_* lookups -------------------------------------------------------
// Tuple order matches the INSERT in seed.ts:
//   (code, name_th, name_en, name_mm, name_zh, sort_order)
const s = (v) => (v == null ? '' : String(v))

function genLabel(srcFile, outFile, constName, { synthCode }) {
  const rows = read(srcFile)
  const tuples = rows.map((r) => {
    const code = synthCode ? String(r.id).padStart(4, '0') : s(r.code)
    return [code, s(r.name_th), s(r.name_en), s(r.name_mm), s(r.name_zh), Number(r.sort_order) || 0]
  })
  const body =
    header(srcFile) +
    `// [code, name_th, name_en, name_mm, name_zh, sort_order]\n` +
    `const ${constName}: [string, string, string, string, string, number][] = ${JSON.stringify(tuples, null, 0)}\n\n` +
    `export default ${constName}\n`
  writeFileSync(join(out, outFile), body)
  console.log(`${outFile}: ${tuples.length} rows${synthCode ? ' (code synthesized from id)' : ''}`)
}

genLabel('label_frequencies.json',    'label-frequencies.ts',     'LABEL_FREQUENCIES',     { synthCode: false })
genLabel('label_meal_relations.json', 'label-meal-relations.ts',  'LABEL_MEAL_RELATIONS',  { synthCode: false })
genLabel('label_advices.json',        'label-advices.ts',         'LABEL_ADVICES',         { synthCode: true })
genLabel('label_dosages.json',        'label-dosages.ts',         'LABEL_DOSAGES',         { synthCode: true })
genLabel('label_times.json',          'label-times.ts',           'LABEL_TIMES',           { synthCode: true })

console.log('done.')
