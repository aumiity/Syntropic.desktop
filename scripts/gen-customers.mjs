// One-shot / regenerable transform: docs/Person.json → electron/db/seed-data/customers.ts
//
// Source: docs/Person.json (converted once from docs/Person.xlsx — Hygeia
// Person export — and mapped to Syntropic customer fields).
// Output: TS module bundled into main.js by rollup — data travels with the app.
//
// Per-table convention: one gen script per seeded table, kept self-contained.
// Adding a new table → create scripts/gen-<table>.mjs alongside this one.
//
// Run: node scripts/gen-customers.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const srcFile = join(root, 'docs', 'Person.json')
const outFile = join(root, 'electron', 'db', 'seed-data', 'customers.ts')

const s = (v) => (v == null ? '' : String(v))

const rows = JSON.parse(readFileSync(srcFile, 'utf-8'))
const tuples = rows.map((r) => [
  s(r.code), s(r.full_name), s(r.id_card), s(r.phone), s(r.address),
])

const T = `[string, string, string, string, string]`
const body =
  `// AUTO-GENERATED by scripts/gen-customers.mjs from docs/Person.json\n` +
  `// Do not edit by hand — re-run the generator instead.\n\n` +
  `// Tuple shape:\n` +
  `//   [code, full_name, id_card, phone, address]\n` +
  `const CUSTOMERS: ${T}[] = ${JSON.stringify(tuples, null, 0)}\n\n` +
  `export default CUSTOMERS\n`

writeFileSync(outFile, body)
console.log(`customers.ts: ${tuples.length} rows`)
