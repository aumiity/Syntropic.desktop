// One-shot / regenerable transform: docs/Item.json → electron/db/seed-data/products.ts
//
// Source: docs/Item.json (converted once from docs/Item.xlsx via openpyxl).
// Output: TS module bundled into main.js by rollup — data travels with the app.
//
// Per-table convention: one gen script per seeded table, kept self-contained.
// Adding a new table → create scripts/gen-<table>.mjs alongside this one.
//
// Run: node scripts/gen-products.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const srcFile = join(root, 'docs', 'Item.json')
const outFile = join(root, 'electron', 'db', 'seed-data', 'products.ts')

const s = (v) => (v == null ? '' : String(v))
const n = (v) => Number(v) || 0
const i = (v) => (v ? 1 : 0)

// Drop unusable junk products: names that are blank, numeric-only, code/barcode
// dumps, or "N/A"/"NA"/"xx" placeholders. Real short codes (D2, D5, TDS, PDL)
// have letters and are intentionally kept.
const isJunkName = (name) => {
  const t = s(name).trim()
  if (!t) return true
  if (/^[0-9.\-\/ ]+$/.test(t)) return true // numeric/symbol only
  if (/^[0-9*]+$/.test(t)) return true // barcode-as-name
  if (/^(n\/a|na|xx)$/i.test(t)) return true // placeholders
  return false
}

const rows = JSON.parse(readFileSync(srcFile, 'utf-8'))
const kept = rows.filter((r) => !isJunkName(r.trade_name))
const dropped = rows.length - kept.length
const tuples = kept.map((r) => [
  s(r.code), s(r.trade_name), s(r.name_for_print), s(r.search_keywords),
  s(r.barcode), s(r.barcode2), s(r.barcode3), s(r.barcode4),
  s(r.unit_name),
  n(r.cost_price), n(r.price_retail), n(r.price_wholesale1), n(r.price_wholesale2),
  i(r.is_disabled), i(r.is_hidden), i(r.is_stock_item), i(r.has_vat), i(r.is_drug),
  s(r.tmt_id), s(r.note), n(r.reorder_point),
])

const T = `[string, string, string, string, string, string, string, string, string, number, number, number, number, number, number, number, number, number, string, string, number]`
const body =
  `// AUTO-GENERATED by scripts/gen-products.mjs from docs/Item.json\n` +
  `// Do not edit by hand — re-run the generator instead.\n\n` +
  `// Tuple shape:\n` +
  `//   [code, trade_name, name_for_print, search_keywords,\n` +
  `//    barcode, barcode2, barcode3, barcode4,\n` +
  `//    unit_name, cost_price, price_retail, price_wholesale1, price_wholesale2,\n` +
  `//    is_disabled, is_hidden, is_stock_item, has_vat, is_drug,\n` +
  `//    tmt_id, note, reorder_point]\n` +
  `const PRODUCTS: ${T}[] = ${JSON.stringify(tuples, null, 0)}\n\n` +
  `export default PRODUCTS\n`

writeFileSync(outFile, body)
console.log(`products.ts: ${tuples.length} rows (dropped ${dropped} junk-named)`)
